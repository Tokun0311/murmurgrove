import { readFile, writeFile } from 'node:fs/promises';
import { setTimeout as wait } from 'node:timers/promises';
import { inspect, hasNoindex, key, keyLocation, manifestPath, origin, publicUrl } from './indexnow-content.mjs';

const endpoint = 'https://api.indexnow.org/indexnow';
const home = origin + '/';
const sitemapIndex = origin + '/sitemap-index.xml';
const sitemapFile = origin + '/sitemap-0.xml';
const missingPage = origin + '/.well-known/murmurgrove-indexnow-missing-probe/';
const batchSize = 500;
const maxAttempts = 4;

function requireCondition(condition, message) {
  if (!condition) throw new Error(message);
}

function parseManifest(source) {
  const data = JSON.parse(source);
  requireCondition(data.version === 1 && data.pages && Object.getPrototypeOf(data.pages) === Object.prototype,
    'Invalid IndexNow manifest schema');
  requireCondition(Object.hasOwn(data.pages, home), 'Missing production homepage in manifest');
  for (const [url, hash] of Object.entries(data.pages)) {
    requireCondition(publicUrl(url) === url && /^[0-9a-f]{64}$/.test(hash), 'Invalid manifest entry: ' + url);
  }
  return data;
}

function get(url) {
  return fetch(url, {
    redirect: 'manual',
    headers: { 'Cache-Control': 'no-cache' },
    signal: AbortSignal.timeout(15_000)
  });
}

async function readResponse(url, type) {
  const response = await get(url);
  requireCondition(response.status === 200 && type.test(response.headers.get('content-type') ?? ''),
    'Unexpected production response: ' + response.status + ' ' + url);
  return response.text();
}

// The XML is generated by this repository and contains only escaped URL loc values.
function locations(xml) {
  return [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map(match => match[1].replace(
    /&(amp|lt|gt|quot|apos);/g, (_, entity) => ({ amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" })[entity]
  ));
}

async function checkProductionPage(url, fingerprint) {
  const response = await get(url);
  const headers = response.headers;
  requireCondition(response.status === 200 && /^text\/html\b/i.test(headers.get('content-type') ?? '') &&
    !hasNoindex(headers.get('x-robots-tag')), 'Production page is unavailable or excluded: ' + response.status + ' ' + url);
  const page = inspect(await response.text());
  requireCondition(!page.noindex && page.canonical.length === 1 && page.canonical[0] === url &&
    page.fingerprint === fingerprint, 'Production content differs from manifest: ' + url);
}

async function isRemoved(url) {
  const response = await get(url);
  if ([404, 410].includes(response.status)) return true;
  if ([301, 308].includes(response.status)) {
    const location = response.headers.get('location');
    requireCondition(location && new URL(location, url).href !== url, 'Invalid permanent redirect: ' + url);
    return true;
  }
  if (response.status === 200) {
    if (hasNoindex(response.headers.get('x-robots-tag')) || inspect(await response.text()).noindex) {
      console.log('Leaving explicitly excluded URL out of submission: ' + url);
      return false;
    }
  }
  throw new Error('Previous canonical URL is missing from the manifest but has no confirmed removal: ' +
    response.status + ' ' + url);
}

async function inGroups(items, operation) {
  const results = [];
  for (let offset = 0; offset < items.length; offset += 8) {
    results.push(...await Promise.all(items.slice(offset, offset + 8).map(operation)));
  }
  return results;
}

async function submit(urlList) {
  const payload = JSON.stringify({ host: new URL(origin).host, key, keyLocation, urlList });
  for (let attempt = 1; attempt <= maxAttempts; attempt++) {
    let response;
    try {
      response = await fetch(endpoint, {
        method: 'POST',
        redirect: 'error',
        headers: { 'Content-Type': 'application/json; charset=utf-8' },
        body: payload,
        signal: AbortSignal.timeout(20_000)
      });
    } catch (error) {
      console.error('IndexNow request failed on attempt ' + attempt + ': ' + error.message);
      if (attempt === maxAttempts) throw error;
    }
    let retryAfter = 0;
    if (response) {
      console.log('IndexNow HTTP ' + response.status + ' for ' + urlList.length + ' URLs (attempt ' + attempt + ')');
      if (response.status === 200 || response.status === 202) {
        if (response.status === 202) console.log('IndexNow key validation is pending.');
        await response.body?.cancel();
        return;
      }
      console.error((await response.text()).slice(0, 500));
      const header = response.headers.get('retry-after');
      retryAfter = header && /^\d+$/.test(header) ? Number(header) * 1000 : Date.parse(header) - Date.now();
      if ((response.status !== 429 && response.status < 500) || attempt === maxAttempts || retryAfter > 60_000) {
        throw new Error('IndexNow batch failed with HTTP ' + response.status);
      }
    }
    await wait(Math.max(1000 * 2 ** (attempt - 1), retryAfter || 0));
  }
}

async function main() {
  const options = new Set(process.argv.slice(2));
  requireCondition([...options].every(option => ['--dry-run', '--bootstrap'].includes(option)),
    'Usage: node scripts/submit-indexnow.mjs [--dry-run] [--bootstrap]');
  const state = process.env.INDEXNOW_STATE ?? 'indexnow-state.json';
  let previous;
  try {
    previous = parseManifest(await readFile(state, 'utf8')).pages;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
    requireCondition(options.has('--bootstrap') || options.has('--dry-run'),
      'No previous state. Dispatch the workflow once with bootstrap enabled.');
    previous = {};
  }
  const manifestUrl = origin + manifestPath;
  const manifest = await readResponse(manifestUrl, /^application\/json\b/i);
  const { pages: current, commit } = parseManifest(manifest);
  const expectedCommit = process.env.INDEXNOW_EXPECTED_COMMIT;
  requireCondition(!expectedCommit || commit === expectedCommit,
    'Production has not published the successful Cloudflare commit: ' + expectedCommit);
  const [keyBody, index, sitemap, probe] = await Promise.all([
    readResponse(keyLocation, /^text\/plain\b/i),
    readResponse(sitemapIndex, /xml/i),
    readResponse(sitemapFile, /xml/i),
    get(missingPage)
  ]);
  requireCondition(keyBody === key, 'Production verification file does not match the key');
  requireCondition(probe.status === 404, 'Unknown production URL returned ' + probe.status + ' instead of 404');
  await probe.body?.cancel();
  const listed = locations(sitemap).sort();
  requireCondition(JSON.stringify(locations(index)) === JSON.stringify([sitemapFile]) &&
    JSON.stringify(listed) === JSON.stringify(Object.keys(current).sort()), 'Production sitemaps differ from manifest');

  const added = [];
  const updated = [];
  for (const [url, hash] of Object.entries(current)) {
    if (!Object.hasOwn(previous, url)) added.push(url);
    else if (previous[url] !== hash) updated.push(url);
  }
  const absent = Object.keys(previous).filter(url => !Object.hasOwn(current, url));
  const changed = [...added, ...updated];
  // Check each submitted page and the home page. Unchanged pages keep their
  // previously verified fingerprint without re-crawling the entire site hourly.
  await inGroups([...new Set([home, ...changed])], url => checkProductionPage(url, current[url]));
  const removalChecks = await inGroups(absent, isRemoved);
  const removed = absent.filter((_, index) => removalChecks[index]);
  requireCondition(await readResponse(manifestUrl, /^application\/json\b/i) === manifest,
    'Production changed during verification; retry after deployment settles.');

  const urls = [...new Set([...changed, ...removed])].sort();
  console.log('Production verified. Added: ' + added.length + ', changed: ' + updated.length + ', removed: ' + removed.length);
  if (options.has('--dry-run')) {
    console.log(JSON.stringify({ added, updated, removed }, null, 2));
    return;
  }
  for (let offset = 0; offset < urls.length; offset += batchSize) {
    requireCondition(await readResponse(manifestUrl, /^application\/json\b/i) === manifest,
      'Production changed during submission; retry after deployment settles.');
    await submit(urls.slice(offset, offset + batchSize));
  }
  await writeFile(state, manifest);
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
