import assert from 'node:assert/strict';
import { createMurmurgrove } from '../src/lib/murmurgrove.ts';
const concept=(id,title=id)=>({id,data:{title}});
const exhibition=(id,date,concepts,directions)=>({id,data:{title:id,visitedOn:new Date(date),verification:'recorded',concepts,directions,artists:[]}});
const base={exhibitions:[exhibition('a','2026-01-01',['site-specificity'])],institutions:[],people:[],concepts:[concept('site-specificity'),concept('curatorial-practices')],writing:[],photography:[]};
const b=createMurmurgrove(base);
assert.equal(b.counts.exhibitions,1);
assert.equal(b.marks.length,3);
assert(b.roots.some(r=>r.from==='exhibitions:a' && r.to==='concepts:site-specificity'));
const future={...base,exhibitions:[...base.exhibitions,...Array.from({length:1000},(_,i)=>exhibition('e'+i,`2034-01-${String(i%28+1).padStart(2,'0')}`,i%5?'site-specificity'.split(' '):['curatorial-practices']))],writing:[{id:'essay-1',data:{title:'Essay',date:new Date('2034-05-01'),draft:false,concepts:['curatorial-practices'],tags:[]}}, {id:'draft',data:{title:'Draft',draft:true,concepts:['site-specificity']}}]};
const f=createMurmurgrove(future);
assert.equal(f.counts.exhibitions,1001);
assert.equal(f.counts.writing,1);
assert.equal(f.marks.length,1004);
assert(!f.marks.some(m=>m.key==='draft'));
assert.equal(new Set(f.marks.map(m=>m.section+':'+m.key)).size,f.marks.length);
assert(f.roots.some(r=>r.from==='writing:essay-1' && r.to==='concepts:curatorial-practices'));
assert(f.directionStates.find(d=>d.id==='site-specificity').count>b.directionStates.find(d=>d.id==='site-specificity').count);
assert(f.marks.some(m=>m.focus==='curatorial-practices'));
assert(f.marks.every(m=>Number.isFinite(m.x)&&Number.isFinite(m.y)));
const stay={...base,exhibitions:[base.exhibitions[0],exhibition('unrelated','2035-01-01',['curatorial-practices'])]};
const st=createMurmurgrove(stay);
assert(st.directionStates.find(d=>d.id==='site-specificity').active<st.directionStates.find(d=>d.id==='curatorial-practices').active);
console.log('Directional growth tests passed: actual associations, writing, dormant directions, 1000+ exhibitions.');
